const localeCodes: Record<Language, string> = { fr: 'fr-FR', en: 'en-GB', ar: 'ar' };
const weekdayNames: Record<Language, string[]> = {
  fr: ['dimanche', 'lundi', 'mardi', 'mercredi', 'jeudi', 'vendredi', 'samedi'],
  en: ['Sunday', 'Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday'],
  ar: ['الأحد', 'الاثنين', 'الثلاثاء', 'الأربعاء', 'الخميس', 'الجمعة', 'السبت'],
};

export function translate(language: Language, source: string, values?: Record<string, string | number>): string {
  let key = source;
  const extra: Record<string, string | number> = {};
  const progress = source.match(/^(Chargement des modèles OCR…|Lecture de la photo…) (\d+) %$/);
  const regions = source.match(/^Lecture de (\d+) zones de cours…$/);
  const recognitionError = source.match(/^La reconnaissance locale a échoué : (.*)$/);
  if (progress) {
    key = `${progress[1]} {percent} %`;
    extra.percent = progress[2]!;
  } else if (regions) {
    key = 'Lecture de {count} zones de cours…';
    extra.count = regions[1]!;
  } else if (recognitionError) {
    key = 'La reconnaissance locale a échoué : {details}';
    extra.details = recognitionError[1]!;
  }
  let result = language === 'fr' ? source : translations[language][key] ?? source;
  const replacements = { ...extra, ...values };
  if (Object.keys(replacements).length) {
    for (const [keyName, value] of Object.entries(replacements)) {
      result = result.replaceAll(`{${keyName}}`, String(value));
    }
  }
  return result;
}

export function localeCode(language: Language): string {
  return localeCodes[language];
}

export function localizedDay(day: DayDef, language: Language): string {
  const french = weekdayNames.fr[day.weekday];
  return day.name.trim().toLocaleLowerCase('fr') === french
    ? weekdayNames[language][day.weekday] ?? day.name
    : day.name;
}
